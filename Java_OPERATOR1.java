public class Java_OPERATOR1 {

    public static void main(String[] args) {
        int a = 10; 
        int b = 3;
       int sum = a + b;// It add variable a and b 
       int difference = a - b; // substract a and b 
       int product = a * b;  // multiply a and b 
       int quotient = a / b; //divide a and b
       int remainder =a % b; /* remainder of a and b meaning the remaining
       number when dividing two number, since our variable declaration is int 
       it can't account for the decimal 
       */

        System.out.println(sum);
        System.out.println(difference);
        System.out.println(product);
        System.out.println(quotient);
        System.out.println(remainder);
      
       
       
       
       
    }
}
